#!/usr/bin/env python3
"""Build a visual HTML report for a trained PMLD run and open it.

Usage:
  python explain.py                       # default run 'shaker'
  python explain.py --run shaker-test
"""
import argparse
import csv
import html
import os
from pathlib import Path

import cv2
from ultralytics import YOLO

from predict import tiled_predict

HERE = Path(__file__).resolve().parent


def latest_run(root):
    """Newest runs/segment/*/ with both results.csv and weights/best.pt."""
    cands = [d for d in root.glob("*")
             if (d / "results.csv").exists() and (d / "weights" / "best.pt").exists()]
    if not cands:
        raise SystemExit(f"no completed run under {root} (need results.csv + weights/best.pt); run train.py first or pass --run")
    return max(cands, key=lambda p: p.stat().st_mtime)


def last_row(run):
    return list(csv.DictReader((run / "results.csv").open()))[-1]


def key_facts(run):
    r = last_row(run)
    return [
        ("What it detects", "Stone/cuttings regions on a shale shaker (1 class: stone), as pixel masks"),
        ("Model", "YOLO26 instance segmentation"),
        ("Data", "PMLD frames, leak-free temporal 70:20:10 split (see prepare_dataset.py)"),
        ("Best epoch", r["epoch"]),
        ("Mask precision", f"{float(r['metrics/precision(M)']):.0%} of what it segments is real stone"),
        ("Mask recall", f"{float(r['metrics/recall(M)']):.0%} of real stone it catches"),
        ("mAP50 (mask)", f"{float(r['metrics/mAP50(M)']):.0%}"),
        ("mAP50-95 (mask)", f"{float(r['metrics/mAP50-95(M)']):.0%}"),
    ]


def sample_predictions(run, split="test", limit=6, tile=0, overlap=128):
    out = HERE / "runs" / "report"
    out.mkdir(parents=True, exist_ok=True)
    model = YOLO(run / "weights" / "best.pt")
    src = HERE / "dataset" / "images" / split
    rows, covs = [], []
    for p in sorted(src.glob("*.jpg"))[:limit]:
        dst = out / p.name
        if tile:
            img = cv2.imread(str(p))
            canvas, boxes = tiled_predict(model, img, tile, overlap, 0.25)
            cov = float(canvas.sum()) / (img.shape[0] * img.shape[1]) * 100
            for x1, y1, x2, y2 in boxes:
                cv2.rectangle(img, (int(x1), int(y1)), (int(x2), int(y2)), (0, 255, 0), 2)
            cv2.imwrite(str(dst), img)
        else:
            r = model(p, verbose=False, retina_masks=True)[0]
            cov = (float(r.masks.data.sum()) / (r.orig_shape[0] * r.orig_shape[1]) * 100
                   if r.masks is not None else 0.0)
            r.save(filename=str(dst))
        rows.append(dst)
        covs.append(cov)
    return rows, covs


def build(run, tile=0, overlap=128):
    facts = key_facts(run)
    samples, covs = sample_predictions(run, tile=tile, overlap=overlap)
    assets = [
        ("Training curves", run / "results.png"),
        ("Confusion matrix", run / "confusion_matrix.png"),
        ("Precision-Recall curve (mask)", run / "MaskPR_curve.png"),
        ("F1 confidence curve (mask)", run / "MaskF1_curve.png"),
        ("Label ground truth", run / "labels.jpg"),
    ]
    cards = "".join(f'<div class="card"><h3>{html.escape(t)}</h3><img src="{img.resolve()}" /></div>'
                    for t, img in assets if img.exists())
    batches = "".join(
        f'<div class="card"><h3>What training saw ({html.escape(p.name)})</h3><img src="{p.resolve()}" /></div>'
        for p in sorted(run.glob("train_batch*.jpg"))[:3])
    live = "".join(
        f'<div class="card"><h3>{html.escape(p.name[:24])} - stone coverage {c:.1f}%</h3>'
        f'<img src="{p.resolve()}" /></div>' for p, c in zip(samples, covs))
    facts_html = "".join(f"<tr><td>{html.escape(k)}</td><td>{html.escape(v)}</td></tr>" for k, v in facts)
    mean_cov = sum(covs) / len(covs) if covs else 0
    body = f"""<html><head><meta charset="utf-8"><title>PMLD shaker model</title></head>
<body style="font-family:Segoe UI,sans-serif;background:#111;color:#eee;max-width:1000px;margin:auto;padding:20px">
<h1>PMLD shale-shaker stone detector</h1>
<table style="border-collapse:collapse">{facts_html}</table>
{cards}
<h2>Live predictions from the test split</h2>
<b style="color:#ff9">{len(samples)} frames - average stone coverage {mean_cov:.1f}%</b>
{live}
{batches}
<p style="color:#888">Generated by explain.py.</p></body></html>"""
    rep = (run / ".." / f"{run.name}-report.html").resolve()
    rep.write_text(body, encoding="utf-8")
    return rep


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default=None, help="run dir (default: newest completed run under runs/segment)")
    ap.add_argument("--tile", type=int, default=0, help="tile size if the model was trained on tiles")
    ap.add_argument("--overlap", type=int, default=128)
    args = ap.parse_args()
    args.run = args.run or str(latest_run(HERE / "runs" / "segment"))
    html_file = build(Path(args.run), tile=args.tile, overlap=args.overlap)
    print(f"Report: {html_file}")
    os.startfile(html_file)


if __name__ == "__main__":
    main()
